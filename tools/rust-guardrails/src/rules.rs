//! Rule registry: the single source of truth for rule category, default severity and the
//! refactoring playbook used by `report` and `explain`. Severities are defaults; profile
//! adjustments live in `scan::adjust_for_profile`.

use crate::model::{Category, Confidence, Finding, Severity};

pub struct RuleInfo {
    pub id: &'static str,
    pub category: Category,
    pub severity: Severity,
    pub title: &'static str,
    /// Why the signal matters and what would make it a non-issue.
    pub why: &'static str,
    /// When leaving the code as is is the right call.
    pub keep: &'static str,
    pub minimal: &'static str,
    pub structural: &'static str,
    /// Verification steps; `{file}` is substituted by the report.
    pub verify: &'static [&'static str],
    pub reference: &'static str,
    /// Changing this code can alter observable state/ordering: write characterization tests first.
    pub characterize_first: bool,
}

