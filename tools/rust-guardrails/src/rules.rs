pub fn get(id: &str) -> Option<&'static RuleInfo> {
    RULES.iter().find(|r| r.id == id)
}

/// Creates a finding with the registry's category and default severity.
/// Panics in debug builds on an unknown id, so tests catch typos.
pub fn finding(id: &'static str, confidence: Confidence) -> Finding {
    match get(id) {
        Some(r) => Finding::new(id, r.category, r.severity, confidence).msg(r.title),
        None => {
            debug_assert!(false, "unknown rule id {id}");
            Finding::new(id, Category::Quality, Severity::Info, confidence)
        }
    }
}

/// Generic playbook for compiler/clippy diagnostics, keyed by category.
pub struct GenericPlay {
    pub keep: &'static str,
    pub minimal: &'static str,
    pub structural: &'static str,
    pub reference: &'static str,
}

pub fn generic_play(cat: Category) -> GenericPlay {
    let (structural, reference) = match cat {
        Category::Safety => ("Encapsulate unsafe behind a safe API with documented invariants.", "references/anti-patterns.md"),
        Category::Concurrency => ("Rework ownership of the shared state (owner task + bounded channel).", "references/concurrency.md"),
        Category::Ownership => ("Re-examine the data model: split state, IDs, or ownership transfer.", "references/architecture.md"),
        Category::Performance => ("Only with a measured hot path: restructure data flow (see references/performance.md).", "references/performance.md"),
        Category::Architecture => ("Re-draw module boundaries by responsibility.", "references/refactoring.md"),
        Category::Quality => ("n/a for most lints.", "references/verification.md"),
    };
    GenericPlay {
        keep: "The lint's trade-off does not apply here: allow it narrowly with `#[allow(lint)]` and a comment.",
        minimal: "Apply the compiler/clippy suggestion after reading it (`cargo clippy --fix` only on a clean tree; review the diff).",
        structural,
        reference,
    }
}

